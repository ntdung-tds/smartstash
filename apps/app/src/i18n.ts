/** Dịch thuần (dùng ngoài component: service, alert trong handler thường) */
export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? STRINGS.vi[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Hook dịch cho component: tự render lại khi ngôn ngữ trong store đổi */
export function useT(): {
  t: (key: string, params?: Record<string, string | number>) => string;
  lang: Lang;
} {
  const lang = useAppStore((s) => s.lang);
  return { t: (key, params) => translate(lang, key, params), lang };
}
